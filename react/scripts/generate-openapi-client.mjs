import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url))
const reactDirectory = path.resolve(scriptDirectory, '..')
const sourcePath = path.join(reactDirectory, 'src/api/openapi.json')
const outputDirectory = path.join(reactDirectory, 'src/api/generated')
const outputPath = path.join(outputDirectory, 'openapi.ts')
const checkOnly = process.argv.includes('--check')

const document = JSON.parse(fs.readFileSync(sourcePath, 'utf8'))
const sourceHash = crypto
  .createHash('sha256')
  .update(JSON.stringify(document))
  .digest('hex')

function refName(reference) {
  return reference.slice(reference.lastIndexOf('/') + 1)
}

function quoteProperty(property) {
  return /^[A-Za-z_$][\w$]*$/.test(property) ? property : JSON.stringify(property)
}

function nullable(type, schema) {
  return schema?.nullable && !type.includes('null') ? `${type} | null` : type
}

function schemaType(schema, depth = 0) {
  if (!schema) return 'unknown'
  if (schema.$ref) return `components["schemas"][${JSON.stringify(refName(schema.$ref))}]`
  if (schema.enum) {
    const values = schema.enum.map(value => JSON.stringify(value)).join(' | ')
    return nullable(values || 'never', schema)
  }
  if (schema.oneOf || schema.anyOf) {
    const variants = (schema.oneOf ?? schema.anyOf).map(item => schemaType(item, depth)).join(' | ')
    return nullable(variants || 'unknown', schema)
  }
  if (schema.allOf) {
    const variants = schema.allOf.map(item => schemaType(item, depth)).join(' & ')
    return nullable(variants || 'unknown', schema)
  }
  if (schema.type === 'array' || schema.items) {
    return nullable(`Array<${schemaType(schema.items, depth)}>`, schema)
  }
  if (schema.type === 'object' || schema.properties || schema.additionalProperties) {
    const properties = Object.entries(schema.properties ?? {})
    const required = new Set(schema.required ?? [])
    const lines = properties.map(([name, value]) =>
      `${'  '.repeat(depth + 1)}${quoteProperty(name)}${required.has(name) ? '' : '?'}: ${schemaType(value, depth + 1)};`,
    )
    if (schema.additionalProperties) {
      lines.push(`${'  '.repeat(depth + 1)}[key: string]: ${schemaType(schema.additionalProperties, depth + 1)};`)
    }
    return nullable(lines.length ? `{\n${lines.join('\n')}\n${'  '.repeat(depth)}}` : 'Record<string, unknown>', schema)
  }
  switch (schema.type) {
    case 'boolean': return nullable('boolean', schema)
    case 'integer':
    case 'number': return nullable('number', schema)
    case 'string': return nullable('string', schema)
    case 'null': return 'null'
    default: return 'unknown'
  }
}

function operationType(operation) {
  const parameters = operation.parameters?.length
    ? `{ ${operation.parameters.map(parameter => `${quoteProperty(parameter.name)}${parameter.required ? '' : '?'}: ${schemaType(parameter.schema)}`).join('; ')} }`
    : 'never'
  const requestBody = operation.requestBody?.content
    ? Object.values(operation.requestBody.content)[0]?.schema
    : null
  return `{ operationId: ${JSON.stringify(operation.operationId ?? '')}; parameters: ${parameters}; requestBody: ${requestBody ? schemaType(requestBody) : 'never'}; }`
}

const schemas = Object.entries(document.components?.schemas ?? {})
  .map(([name, schema]) => `    ${JSON.stringify(name)}: ${schemaType(schema, 2)};`)
  .join('\n')

const pathEntries = Object.entries(document.paths ?? {}).map(([route, methods]) => {
  const methodEntries = Object.entries(methods)
    .filter(([method]) => !method.startsWith('x-'))
    .map(([method, operation]) => `    ${method}: ${operationType(operation)};`)
    .join('\n')
  return `  ${JSON.stringify(route)}: {\n${methodEntries}\n  };`
}).join('\n')

const operations = Object.entries(document.paths ?? {}).flatMap(([route, methods]) =>
  Object.entries(methods)
    .filter(([method]) => !method.startsWith('x-'))
    .map(([method, operation]) => ({
      path: route,
      method: method.toUpperCase(),
      operationId: operation.operationId ?? '',
    })),
)

const generated = `/* eslint-disable */
// AUTO-GENERATED by scripts/generate-openapi-client.mjs. Do not edit manually.
// Source SHA-256: ${sourceHash}

export const openApiSourceHash = ${JSON.stringify(sourceHash)} as const

export interface components {
  schemas: {
${schemas}
  }
}

export interface paths {
${pathEntries}
}

export const openApiOperations = ${JSON.stringify(operations, null, 2)} as const
`

if (checkOnly) {
  const existing = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : ''
  if (existing !== generated) {
    console.error(`Generated OpenAPI contract is stale: ${path.relative(process.cwd(), outputPath)}`)
    process.exit(1)
  }
} else {
  fs.mkdirSync(outputDirectory, { recursive: true })
  fs.writeFileSync(outputPath, generated)
  console.log(`Generated ${path.relative(process.cwd(), outputPath)}`)
}
